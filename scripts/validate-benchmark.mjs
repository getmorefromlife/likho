#!/usr/bin/env node
/**
 * Semantic validator for Likho prosody benchmark files.
 *
 * The JSON Schema in data/benchmarks/prosody/schema/benchmark.schema.json
 * describes the shape. This validator adds checks that JSON Schema cannot
 * express: meter variants, source-revision identity, token spans, reading
 * patterns, duplicate items, reviewer references, adjudication invariants,
 * frozen-status support thresholds and optional on-disk pin verification.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';

export const SCHEMA_VERSION = '1.0.0';
export const SUPPORTED_METER_MINIMUM = 10;
const ITEM_ID = /^LKH-PRO-[0-9]{4}$/;
const METER_ID = /^[a-z0-9][a-z0-9-]*$/;
const ANALYSIS_ID = /^A[0-9]+$/;
const REVIEWER_ID = /^rev-[a-z0-9-]+$/;
const SHA256 = /^[0-9a-f]{64}$/;
const PATTERN = /^[-=]+$/;
const DATE = /^[0-9]{4}-[0-9]{2}-[0-9]{2}$/;

const isObject = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const isDate = value => typeof value === 'string' && DATE.test(value) && !Number.isNaN(Date.parse(value));
const isSemver = value => typeof value === 'string' && /^[0-9]+\.[0-9]+\.[0-9]+$/.test(value);
const canonicalText = text => text.normalize('NFC').replace(/\s+/gu, ' ').trim();
const looseText = text => text.normalize('NFC').replace(/[\p{P}\p{S}\s]/gu, '');
const canonicalFileDigest = files => createHash('sha256')
  .update([...files].sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0)
    .map(file => file.path + '\0' + file.sha256 + '\n').join(''))
  .digest('hex');
const fileSha256 = path => createHash('sha256').update(readFileSync(path)).digest('hex');

/** Recreate the documented variants generated by scanMeter. */
export function meterPatternVariants(meter) {
  const variants = [{ feet: [...meter.patternsList], notes: [] }];
  if (meter.initialFlexible) variants.push({
    feet: ['-' + meter.patternsList[0].slice(1), ...meter.patternsList.slice(1)],
    notes: ['initial-short']
  });
  if (meter.caesuraAfter) {
    for (const variant of [...variants]) {
      const feet = [...variant.feet];
      feet[meter.caesuraAfter - 1] += '-';
      variants.push({ feet, notes: [...variant.notes, 'caesura-short'] });
    }
  }
  if (meter.allowTerminalShort) {
    for (const variant of [...variants]) {
      const feet = [...variant.feet];
      feet[feet.length - 1] += '-';
      variants.push({ feet, notes: [...variant.notes, 'terminal-short'] });
    }
  }
  return variants.map(variant => ({ pattern: variant.feet.join(''), notes: variant.notes }));
}

let meterModule;
export async function loadMeters(rootDir = process.cwd()) {
  if (!meterModule) {
    const outfile = join(mkdtempSync(join(tmpdir(), 'likho-benchmark-meters-')), 'meters.mjs');
    await build({
      stdin: {
        contents: `export { CLASSICAL_BUHUR } from './src/data/prosodyMeters';`,
        resolveDir: rootDir
      },
      bundle: true,
      platform: 'node',
      format: 'esm',
      outfile
    });
    meterModule = await import(pathToFileURL(outfile).href);
  }
  return meterModule.CLASSICAL_BUHUR;
}

export function validateBenchmark(data, options = {}) {
  const errors = [];
  const warnings = [];
  const fail = (code, path, message) => errors.push({ code, path, message });
  const warn = (code, path, message) => warnings.push({ code, path, message });
  const stats = {
    items: 0,
    analyses: 0,
    readings: 0,
    classifications: {},
    meters: {},
    authors: [],
    sourceRevisions: 0
  };

  if (!isObject(data)) {
    fail('data-not-object', '$', 'Benchmark document must be an object.');
    return { ok: false, errors, warnings, stats };
  }
  if (data.schemaVersion !== SCHEMA_VERSION) {
    fail('schema-version', '$.schemaVersion', `Expected schemaVersion ${SCHEMA_VERSION}.`);
  }
  if (!isObject(data.benchmark)) {
    fail('benchmark-missing', '$.benchmark', 'benchmark must be an object.');
    return { ok: false, errors, warnings, stats };
  }
  if (!Array.isArray(data.items) || !data.items.length) {
    fail('items-empty', '$.items', 'items must be a non-empty array.');
    return { ok: false, errors, warnings, stats };
  }

  const benchmark = data.benchmark;
  if (!/^lkh-prosody-[a-z0-9-]+$/.test(benchmark.id || '')) {
    fail('benchmark-id', '$.benchmark.id', 'benchmark.id must match lkh-prosody-[a-z0-9-]+.');
  }
  if (!isSemver(benchmark.version)) {
    fail('benchmark-version', '$.benchmark.version', 'benchmark.version must be semantic version x.y.z.');
  }
  if (typeof benchmark.title !== 'string' || !benchmark.title.trim()) {
    fail('benchmark-title', '$.benchmark.title', 'benchmark.title must be non-empty.');
  }
  if (!['internal-pilot', 'draft', 'frozen', 'retired'].includes(benchmark.status)) {
    fail('benchmark-status', '$.benchmark.status', 'benchmark.status is not a recognised status.');
  }
  if (!isDate(benchmark.createdAt)) {
    fail('benchmark-date', '$.benchmark.createdAt', 'benchmark.createdAt must be an ISO date.');
  }
  if (!isObject(benchmark.protocol) || !benchmark.protocol.id || !isSemver(benchmark.protocol.version) || !benchmark.protocol.path) {
    fail('protocol-reference', '$.benchmark.protocol', 'Protocol id, version and path are required.');
  } else if (options.rootDir && !existsSync(resolve(options.rootDir, benchmark.protocol.path))) {
    fail('protocol-path-missing', '$.benchmark.protocol.path', 'Protocol path does not exist.');
  }
  if (!isObject(benchmark.scope) || benchmark.scope.language !== 'ur' || benchmark.scope.script !== 'Arab') {
    fail('scope-language', '$.benchmark.scope', 'Scope must declare Urdu in Arabic script.');
  }
  if (!isObject(benchmark.engine)) {
    fail('engine-missing', '$.benchmark.engine', 'Engine pin is required.');
  }
  if (!isObject(benchmark.review)) {
    fail('review-missing', '$.benchmark.review', 'Review block is required.');
  }

  const reviewers = new Map();
  if (isObject(benchmark.review) && Array.isArray(benchmark.review.reviewers)) {
    for (const [index, reviewer] of benchmark.review.reviewers.entries()) {
      const path = `$.benchmark.review.reviewers[${index}]`;
      if (!isObject(reviewer)) {
        fail('reviewer-shape', path, 'Reviewer must be an object.');
        continue;
      }
      if (!REVIEWER_ID.test(reviewer.id || '')) {
        fail('reviewer-id', `${path}.id`, 'Reviewer id must match rev-[a-z0-9-]+.');
      } else if (reviewers.has(reviewer.id)) {
        fail('reviewer-duplicate', `${path}.id`, 'Reviewer id must be unique.');
      } else {
        reviewers.set(reviewer.id, reviewer);
      }
      if (!['annotator', 'annotator-verifier', 'adjudicator', 'verifier'].includes(reviewer.role)) {
        fail('reviewer-role', `${path}.role`, 'Reviewer role is not recognised.');
      }
      if (!['internal-engine-author', 'qualified-prosody-reviewer', 'editorial-reviewer'].includes(reviewer.qualification)) {
        fail('reviewer-qualification', `${path}.qualification`, 'Reviewer qualification is not recognised.');
      }
      if (reviewer.independent === true && reviewer.qualification !== 'qualified-prosody-reviewer') {
        fail('reviewer-independence-mismatch', `${path}`, 'An independent prosody reviewer must have qualified-prosody-reviewer qualification.');
      }
      if (reviewer.independent === false && reviewer.qualification === 'qualified-prosody-reviewer') {
        fail('reviewer-independence-mismatch', `${path}`, 'A qualified-prosody-reviewer must be marked independent.');
      }
    }
  }

  const review = isObject(benchmark.review) ? benchmark.review : {};
  if (!['unreviewed', 'single-annotator', 'independent-double'].includes(review.mode)) {
    fail('review-mode', '$.benchmark.review.mode', 'Review mode is not recognised.');
  }
  if (review.mode === 'unreviewed') {
    if (Array.isArray(review.reviewers) && review.reviewers.length) {
      fail('unreviewed-has-reviewers', '$.benchmark.review.reviewers', 'Unreviewed benchmark must not list reviewers.');
    }
  }
  if (review.mode === 'single-annotator' && (!Array.isArray(review.reviewers) || !review.reviewers.length)) {
    fail('single-annotator-empty', '$.benchmark.review.reviewers', 'Single-annotator mode requires at least one reviewer.');
  }
  if (review.mode === 'independent-double') {
    const independent = (review.reviewers || []).filter(reviewer => reviewer.independent === true && reviewer.qualification === 'qualified-prosody-reviewer');
    if (independent.length < 2) {
      fail('review-double-underpowered', '$.benchmark.review.reviewers', 'Independent-double mode requires at least two independent qualified prosody reviewers.');
    }
    if (!isObject(review.adjudicator)) {
      fail('review-double-no-adjudicator', '$.benchmark.review.adjudicator', 'Independent-double mode requires an adjudicator.');
    } else if (independent.some(reviewer => reviewer.id === review.adjudicator.id)) {
      fail('review-double-adjudicator-overlap', '$.benchmark.review.adjudicator', 'Adjudicator must be distinct from annotators.');
    }
    if (review.blindToEngineOutput !== true) {
      fail('review-double-not-blind', '$.benchmark.review.blindToEngineOutput', 'Independent-double annotation must be blind to engine output.');
    }
    if (review.annotationBasis === 'engine-assisted-internal') {
      fail('review-double-engine-assisted', '$.benchmark.review.annotationBasis', 'Independent-double annotation cannot be engine-assisted.');
    }
  }
  if (review.annotationBasis === 'blind-human' && review.blindToEngineOutput !== true) {
    fail('review-basis-conflict', '$.benchmark.review', 'A blind-human basis requires blindToEngineOutput true.');
  }
  if (review.annotationBasis === 'engine-assisted-internal' && review.blindToEngineOutput === true) {
    fail('review-basis-conflict', '$.benchmark.review', 'An engine-assisted-internal basis cannot be marked blind.');
  }
  if (review.mode !== 'unreviewed' && (review.independenceStatement || '').trim().length === 0) {
    fail('review-independence-statement', '$.benchmark.review.independenceStatement', 'An independence statement is required.');
  }
  if (benchmark.status === 'internal-pilot' && (!Array.isArray(review.limitations) || !review.limitations.length)) {
    fail('review-limitations', '$.benchmark.review.limitations', 'An internal pilot must state its limitations.');
  }
  if (isObject(review.effortObservation)) {
    const effort = review.effortObservation;
    if (effort.measured === true && !(typeof effort.minutesPerItem === 'number' && effort.minutesPerItem > 0)) {
      fail('effort-observation-inconsistent', '$.benchmark.review.effortObservation', 'Measured effort requires a positive minutesPerItem.');
    }
    if (effort.measured === false && effort.minutesPerItem !== null) {
      fail('effort-observation-inconsistent', '$.benchmark.review.effortObservation', 'Unmeasured effort must record minutesPerItem as null.');
    }
  } else {
    fail('effort-observation-missing', '$.benchmark.review.effortObservation', 'Effort observation is required.');
  }
  if (review.adjudicationStatus === 'complete') {
    if (!isObject(review.adjudicator)) {
      fail('adjudication-complete-without-adjudicator', '$.benchmark.review.adjudicator', 'Complete adjudication requires an adjudicator.');
    }
  }
  if (benchmark.status === 'frozen') {
    if (review.mode !== 'independent-double') {
      fail('frozen-review-mode', '$.benchmark.review.mode', 'Frozen benchmarks require independent double annotation.');
    }
    if (review.blindToEngineOutput !== true || review.annotationBasis !== 'blind-human') {
      fail('frozen-review-basis', '$.benchmark.review', 'Frozen benchmarks require blind human annotation.');
    }
    if (review.adjudicationStatus !== 'complete') {
      fail('frozen-adjudication-status', '$.benchmark.review.adjudicationStatus', 'Frozen benchmarks require complete adjudication.');
    }
  }

  const engine = isObject(benchmark.engine) ? benchmark.engine : {};
  if (!/^[0-9a-f]{7,40}$/.test(engine.appCommit || '')) {
    fail('engine-commit', '$.benchmark.engine.appCommit', 'Engine commit must be 7-40 lowercase hex characters.');
  }
  if (typeof engine.workingTreeDirty !== 'boolean') {
    fail('engine-dirty-flag', '$.benchmark.engine.workingTreeDirty', 'workingTreeDirty must be boolean.');
  }
  if (!isObject(engine.lexicon) || !engine.lexicon.source || !engine.lexicon.revision || !SHA256.test(engine.lexicon.sha256 || '') || !SHA256.test(engine.lexicon.sourceSha256 || '') || !engine.lexicon.license || !(engine.lexicon.words > 0)) {
    fail('engine-lexicon', '$.benchmark.engine.lexicon', 'Lexicon source, revision, runtime sha256, source sha256, license and word count are required.');
  }
  if (!isObject(engine.meterTable) || !engine.meterTable.path || !SHA256.test(engine.meterTable.sha256 || '')) {
    fail('engine-meter-table', '$.benchmark.engine.meterTable', 'Meter-table path and sha256 are required.');
  }
  if (!isObject(engine.sourceDigest) || engine.sourceDigest.algorithm !== 'sha256' || !Array.isArray(engine.sourceDigest.files) || !engine.sourceDigest.files.length || !SHA256.test(engine.sourceDigest.digest || '')) {
    fail('engine-source-digest', '$.benchmark.engine.sourceDigest', 'Source digest requires algorithm, files and digest.');
  } else {
    const seen = new Set();
    for (const [index, file] of engine.sourceDigest.files.entries()) {
      const path = `$.benchmark.engine.sourceDigest.files[${index}]`;
      if (!isObject(file) || !file.path || !SHA256.test(file.sha256 || '')) {
        fail('engine-source-file', path, 'Each digest file needs a path and sha256.');
        continue;
      }
      if (seen.has(file.path)) fail('engine-source-duplicate', path, 'Digest file paths must be unique.');
      seen.add(file.path);
    }
    const expectedDigest = canonicalFileDigest(engine.sourceDigest.files.filter(file => isObject(file) && file.path && SHA256.test(file.sha256 || '')));
    if (expectedDigest !== engine.sourceDigest.digest) {
      fail('source-digest-mismatch', '$.benchmark.engine.sourceDigest.digest', 'Digest does not match the canonical hash of the listed file pins.');
    }
  }

  const meters = Array.isArray(options.meters) ? options.meters : null;
  const meterMap = new Map((meters || []).map(meter => [meter.id, meter]));

  if (options.rootDir && isObject(engine)) {
    const verifyFile = (path, expected, code, label) => {
      const absolute = resolve(options.rootDir, path);
      if (!existsSync(absolute)) {
        fail(code, label, `Pinned file does not exist: ${path}`);
        return;
      }
      const actual = fileSha256(absolute);
      if (actual !== expected) fail(code, label, `Pinned hash does not match ${path}.`);
    };
    if (isObject(engine.lexicon)) {
      verifyFile('src/data/prosody/aruuz-dictionary.json', engine.lexicon.sha256, 'lexicon-hash-mismatch', '$.benchmark.engine.lexicon.sha256');
      const metaPath = resolve(options.rootDir, 'src/data/prosody/aruuz-dictionary.meta.json');
      if (existsSync(metaPath)) {
        try {
          const meta = JSON.parse(readFileSync(metaPath, 'utf8'));
          if (meta.sha256 !== engine.lexicon.sourceSha256) fail('lexicon-meta-mismatch', '$.benchmark.engine.lexicon.sourceSha256', 'Lexicon meta source sha256 does not match the engine pin.');
          if (meta.revision !== engine.lexicon.revision) fail('lexicon-meta-mismatch', '$.benchmark.engine.lexicon.revision', 'Lexicon meta revision does not match the engine pin.');
          if (meta.words !== engine.lexicon.words) fail('lexicon-meta-mismatch', '$.benchmark.engine.lexicon.words', 'Lexicon meta word count does not match the engine pin.');
        } catch (error) {
          fail('lexicon-meta-invalid', '$.benchmark.engine.lexicon', `Lexicon metadata could not be read: ${error.message}`);
        }
      }
    }
    if (isObject(engine.meterTable)) {
      verifyFile(engine.meterTable.path, engine.meterTable.sha256, 'meter-table-hash-mismatch', '$.benchmark.engine.meterTable.sha256');
    }
    if (isObject(engine.sourceDigest) && Array.isArray(engine.sourceDigest.files)) {
      for (const [index, file] of engine.sourceDigest.files.entries()) {
        if (isObject(file) && file.path && SHA256.test(file.sha256 || '')) {
          verifyFile(file.path, file.sha256, 'source-file-hash-mismatch', `$.benchmark.engine.sourceDigest.files[${index}].sha256`);
        }
      }
    }
  }

  const seenItemIds = new Map();
  const seenTexts = new Map();
  const seenLooseTexts = new Map();
  const poemSplits = new Map();
  const authors = new Set();
  const revisions = new Set();
  const supportedCounts = new Map();
  const declaredSupportedMeters = new Set();
  let anyPendingItem = false;

  for (const [index, item] of data.items.entries()) {
    const path = `$.items[${index}]`;
    if (!isObject(item)) {
      fail('item-shape', path, 'Item must be an object.');
      continue;
    }
    stats.items++;
    if (!ITEM_ID.test(item.id || '')) {
      fail('item-id', `${path}.id`, 'Item id must match LKH-PRO-NNNN.');
    } else if (seenItemIds.has(item.id)) {
      fail('duplicate-item-id', `${path}.id`, `Item id ${item.id} is duplicated (first at ${seenItemIds.get(item.id)}).`);
    } else {
      seenItemIds.set(item.id, path);
    }
    if (typeof item.text !== 'string' || !item.text.trim()) {
      fail('item-text', `${path}.text`, 'Item text must be non-empty.');
    } else {
      if (item.text !== item.text.normalize('NFC')) fail('text-not-nfc', `${path}.text`, 'Item text must be NFC-normalized.');
      if (item.text !== item.text.trim()) fail('text-whitespace', `${path}.text`, 'Item text must not have leading or trailing whitespace.');
      const key = canonicalText(item.text);
      if (seenTexts.has(key)) fail('duplicate-item-text', `${path}.text`, `Text duplicates ${seenTexts.get(key)}.`);
      else seenTexts.set(key, path);
      const loose = looseText(item.text);
      if (seenLooseTexts.has(loose)) warn('duplicate-loose-text', `${path}.text`, `Text differs only by punctuation or spacing from ${seenLooseTexts.get(loose)}.`);
      else seenLooseTexts.set(loose, path);
    }
    if (item.language !== 'ur' || item.script !== 'Arab' || item.unicodeNormalization !== 'NFC') {
      fail('item-language', path, 'Item must declare Urdu, Arabic script and NFC normalization.');
    }

    const source = isObject(item.source) ? item.source : {};
    if (!['wikisource-revision', 'print-edition', 'consented-contemporary', 'constructed'].includes(source.kind)) {
      fail('source-kind', `${path}.source.kind`, 'Source kind is not recognised.');
    }
    if (!source.title || !source.author) fail('source-identity', `${path}.source`, 'Source title and author are required.');
    if (!['public-domain', 'licensed', 'consented', 'constructed'].includes(source.rightsStatus)) {
      fail('source-rights-status', `${path}.source.rightsStatus`, 'Rights status is not recognised.');
    }
    if (!source.rightsBasis || !source.license) fail('source-rights-basis', `${path}.source`, 'Rights basis and license are required.');
    if (source.rightsStatus === 'public-domain' && !Number.isInteger(source.authorDeathYear)) {
      fail('source-public-domain-author', `${path}.source.authorDeathYear`, 'Public-domain items require an author death year.');
    }
    if (source.kind === 'wikisource-revision') {
      let parsed;
      try {
        parsed = new URL(source.url);
      } catch {
        fail('source-url', `${path}.source.url`, 'Wikisource source URL is not valid.');
      }
      if (parsed) {
        if (parsed.protocol !== 'https:') fail('source-url-scheme', `${path}.source.url`, 'Source URL must use HTTPS.');
        if (parsed.hostname !== 'ur.wikisource.org') fail('source-url-host', `${path}.source.url`, 'Source URL must be ur.wikisource.org.');
        const oldid = parsed.searchParams.get('oldid');
        if (!oldid || Number(oldid) !== source.revisionId) {
          fail('source-oldid-mismatch', `${path}.source`, 'URL oldid must equal source.revisionId.');
        }
        if (!/^\/wiki\/|^\/w\/index\.php$/.test(parsed.pathname)) {
          fail('source-url-path', `${path}.source.url`, 'Source URL must address a Wikisource page or index.php revision.');
        }
      }
      if (!Number.isInteger(source.revisionId) || source.revisionId < 1) {
        fail('source-revision', `${path}.source.revisionId`, 'A positive Wikisource revision id is required.');
      }
      if (!isDate(source.retrievedAt)) {
        fail('source-retrieved-at', `${path}.source.retrievedAt`, 'A retrieval date is required.');
      }
      revisions.add(source.revisionId + '|' + source.url);
      authors.add(source.author);
    }
    if (source.rightsStatus === 'public-domain' && Number.isInteger(source.publicationYear) && Number.isInteger(source.authorDeathYear) && source.publicationYear < source.authorDeathYear) {
      // Publication before death is normal, so this is informational only.
    }

    const provenance = isObject(item.provenance) ? item.provenance : {};
    if (!/^[a-z0-9][a-z0-9-]*$/.test(provenance.poemId || '')) {
      fail('poem-id', `${path}.provenance.poemId`, 'poemId must be a lowercase stable identifier.');
    }
    if (!['pilot', 'dev', 'locked', 'challenge'].includes(provenance.split)) {
      fail('poem-split-value', `${path}.provenance.split`, 'Split is not recognised.');
    }
    if (!Number.isInteger(provenance.verseLineIndex) || provenance.verseLineIndex < 1 || !Number.isInteger(provenance.coupletIndex) || provenance.coupletIndex < 1) {
      fail('poem-position', `${path}.provenance`, 'Verse and couplet indices must be positive integers.');
    }
    if (!['first', 'second'].includes(provenance.half)) {
      fail('poem-half', `${path}.provenance.half`, 'Half must be first or second.');
    }
    if (!['source-exact', 'source-normalized', 'constructed', 'unfinished'].includes(provenance.textStatus)) {
      fail('poem-text-status', `${path}.provenance.textStatus`, 'Text status is not recognised.');
    }
    if (provenance.poemId && provenance.split) {
      const previous = poemSplits.get(provenance.poemId);
      if (previous && previous !== provenance.split) {
        fail('poem-split-leak', `${path}.provenance.split`, `Poem ${provenance.poemId} appears in both ${previous} and ${provenance.split}.`);
      } else {
        poemSplits.set(provenance.poemId, provenance.split);
      }
    }
    if (benchmark.status === 'internal-pilot' && provenance.split !== 'pilot') {
      fail('pilot-split', `${path}.provenance.split`, 'Internal-pilot items must use the pilot split.');
    }

    const target = isObject(item.target) ? item.target : {};
    const targetMeter = meterMap.get(target.meterId);
    if (meters && !targetMeter) {
      fail('target-meter-unknown', `${path}.target.meterId`, `Meter ${target.meterId} is not in the supported meter table.`);
    }
    if (!METER_ID.test(target.meterId || '')) {
      fail('target-meter-id', `${path}.target.meterId`, 'Meter id is malformed.');
    }
    if (!PATTERN.test(target.targetPattern || '')) {
      fail('target-pattern', `${path}.target.targetPattern`, 'Target pattern must contain only - and =.');
    }
    if (targetMeter) {
      const variants = meterPatternVariants(targetMeter);
      if (!variants.some(variant => variant.pattern === target.targetPattern)) {
        fail('target-pattern-unknown', `${path}.target.targetPattern`, 'Target pattern is not a documented variant of the selected meter.');
      }
      if (target.family !== targetMeter.id.split('-')[0]) {
        fail('target-family-mismatch', `${path}.target.family`, 'Target family does not match the meter id prefix.');
      }
      if (target.meterNameUrdu !== targetMeter.nameUrdu || target.meterNameEnglish !== targetMeter.nameEnglish) {
        fail('target-meter-name-mismatch', `${path}.target`, 'Meter names do not match the meter table.');
      }
    }
    if (typeof target.supported !== 'boolean') {
      fail('target-supported', `${path}.target.supported`, 'target.supported must be boolean.');
    }
    if (benchmark.status === 'internal-pilot' && target.supported === true) {
      fail('pilot-claims-support', `${path}.target.supported`, 'An internal pilot cannot claim benchmark support for a form.');
    }

    const expectation = isObject(item.expectation) ? item.expectation : {};
    if (!['admissible', 'invalid-against-target', 'invalid-against-all-supported-meters', 'unresolved', 'out-of-scope'].includes(expectation.classification)) {
      fail('expectation-classification', `${path}.expectation.classification`, 'Expectation classification is not recognised.');
    }
    if (!['pilot-unadjudicated', 'adjudicated-gold', 'disputed', 'rejected'].includes(expectation.goldStatus)) {
      fail('expectation-gold-status', `${path}.expectation.goldStatus`, 'Gold status is not recognised.');
    }
    if (!Array.isArray(expectation.admissibleAnalysisIds)) {
      fail('expectation-analysis-ids', `${path}.expectation.admissibleAnalysisIds`, 'admissibleAnalysisIds must be an array.');
    }
    const classification = expectation.classification;
    stats.classifications[classification] = (stats.classifications[classification] || 0) + 1;
    if (expectation.goldStatus === 'adjudicated-gold') {
      if (benchmark.status === 'internal-pilot') {
        fail('pilot-gold-claim', `${path}.expectation.goldStatus`, 'An internal pilot cannot contain adjudicated gold items.');
      }
      if (!['agreed', 'resolved'].includes(item.adjudication?.status)) {
        fail('gold-without-adjudication', `${path}.expectation.goldStatus`, 'Adjudicated gold requires agreed or resolved item adjudication.');
      }
      if (!item.adjudication?.selectedAnalysisId) {
        fail('gold-without-selected-analysis', `${path}.expectation.goldStatus`, 'Adjudicated gold requires a selected analysis.');
      }
      if (benchmark.status === 'frozen' && target.supported === false) {
        fail('gold-on-unsupported-meter', `${path}.expectation.goldStatus`, 'A frozen benchmark cannot claim gold on an unsupported form.');
      }
    }
    if (benchmark.status === 'frozen' && expectation.goldStatus === 'pilot-unadjudicated') {
      fail('frozen-unadjudicated-item', `${path}.expectation.goldStatus`, 'Frozen benchmarks cannot contain pilot-unadjudicated items.');
    }

    const analyses = Array.isArray(item.analyses) ? item.analyses : [];
    const analysisMap = new Map();
    for (const [analysisIndex, analysis] of analyses.entries()) {
      const analysisPath = `${path}.analyses[${analysisIndex}]`;
      stats.analyses++;
      if (!isObject(analysis)) {
        fail('analysis-shape', analysisPath, 'Analysis must be an object.');
        continue;
      }
      if (!ANALYSIS_ID.test(analysis.id || '')) {
        fail('analysis-id', `${analysisPath}.id`, 'Analysis id must match A<number>.');
      } else if (analysisMap.has(analysis.id)) {
        fail('analysis-id-duplicate', `${analysisPath}.id`, 'Analysis id must be unique within an item.');
      } else {
        analysisMap.set(analysis.id, analysis);
      }
      if (!['admissible', 'rejected', 'disputed'].includes(analysis.status)) {
        fail('analysis-status', `${analysisPath}.status`, 'Analysis status is not recognised.');
      }
      const analysisMeter = meterMap.get(analysis.meterId);
      if (meters && !analysisMeter) {
        fail('analysis-meter-unknown', `${analysisPath}.meterId`, `Meter ${analysis.meterId} is not in the supported meter table.`);
      }
      if (analysis.meterId === target.meterId && analysis.targetPattern !== target.targetPattern) {
        fail('analysis-target-mismatch', `${analysisPath}.targetPattern`, 'Analysis on the item target meter must use the item target pattern.');
      }
      if (analysisMeter) {
        const variants = meterPatternVariants(analysisMeter);
        if (!variants.some(variant => variant.pattern === analysis.targetPattern)) {
          fail('analysis-target-pattern-unknown', `${analysisPath}.targetPattern`, 'Analysis target pattern is not a documented meter variant.');
        }
        const matching = variants.filter(variant => variant.pattern === analysis.targetPattern);
        if (matching.length && Array.isArray(analysis.meterNotes) && analysis.meterNotes.length && !matching.some(variant => variant.notes.join(',') === analysis.meterNotes.join(','))) {
          warn('analysis-meter-notes', `${analysisPath}.meterNotes`, 'Meter notes do not match a documented variant for this pattern.');
        }
      }
      if (!PATTERN.test(analysis.actualPattern || '')) {
        fail('analysis-actual-pattern', `${analysisPath}.actualPattern`, 'Actual pattern must contain only - and =.');
      }
      if (!Number.isInteger(analysis.distance) || analysis.distance < 0) {
        fail('analysis-distance', `${analysisPath}.distance`, 'Distance must be a non-negative integer.');
      }
      if (analysis.distance === 0 && analysis.actualPattern !== analysis.targetPattern) {
        fail('analysis-distance-zero-pattern', `${analysisPath}`, 'Distance 0 requires actualPattern to equal targetPattern.');
      }
      if (analysis.distance > 0 && analysis.actualPattern === analysis.targetPattern) {
        warn('analysis-distance-positive-pattern', `${analysisPath}.distance`, 'Identical patterns are recorded with a positive distance.');
      }
      if (analysis.status === 'admissible' && analysis.distance !== 0) {
        fail('admissible-analysis-distance', `${analysisPath}.distance`, 'An admissible analysis must have distance 0.');
      }

      const readings = Array.isArray(analysis.readings) ? analysis.readings : [];
      if (!readings.length) {
        fail('analysis-readings-empty', `${analysisPath}.readings`, 'An analysis must contain word readings.');
      }
      let lastEnd = 0;
      for (const [readingIndex, reading] of readings.entries()) {
        const readingPath = `${analysisPath}.readings[${readingIndex}]`;
        stats.readings++;
        if (!isObject(reading)) {
          fail('reading-shape', readingPath, 'Reading must be an object.');
          continue;
        }
        if (reading.tokenIndex !== readingIndex) {
          fail('reading-token-index', `${readingPath}.tokenIndex`, 'Token indices must be contiguous and start at 0.');
        }
        if (typeof reading.text !== 'string' || !reading.text) {
          fail('reading-text', `${readingPath}.text`, 'Reading text must be non-empty.');
        }
        if (typeof reading.normalizedText !== 'string' || !reading.normalizedText) {
          fail('reading-normalized-text', `${readingPath}.normalizedText`, 'Normalized text must be non-empty.');
        }
        if (!Number.isInteger(reading.charStart) || !Number.isInteger(reading.charEnd) || reading.charStart < 0 || reading.charEnd <= reading.charStart) {
          fail('reading-span', `${readingPath}`, 'Reading character span is invalid.');
        } else {
          if (item.text && reading.charEnd > item.text.length) {
            fail('reading-span-bounds', `${readingPath}`, 'Reading span exceeds the item text.');
          } else if (item.text && item.text.slice(reading.charStart, reading.charEnd) !== reading.text) {
            fail('reading-span-mismatch', `${readingPath}`, 'Reading span does not slice the exact reading text.');
          }
          if (reading.charStart < lastEnd) {
            fail('reading-span-overlap', `${readingPath}`, 'Reading spans must be ordered and non-overlapping.');
          }
          lastEnd = Math.max(lastEnd, reading.charEnd);
        }
        if (!PATTERN.test(reading.readingPattern || '')) {
          fail('reading-pattern', `${readingPath}.readingPattern`, 'Reading pattern must contain only - and =.');
        }
        if (!Array.isArray(reading.rules) || reading.rules.some(rule => !/^[a-z0-9-]+$/.test(rule))) {
          fail('reading-rules', `${readingPath}.rules`, 'Rules must be lowercase identifiers.');
        }
        if (!Array.isArray(reading.sourceIds) || !reading.sourceIds.length) {
          fail('reading-source-ids', `${readingPath}.sourceIds`, 'At least one source id is required.');
        }
        if (!['dictionary', 'vocalized', 'user-entry', 'reviewed-entry', 'unresolved'].includes(reading.source)) {
          fail('reading-source', `${readingPath}.source`, 'Reading source is not recognised.');
        }
        if (analysis.status === 'admissible' && reading.source === 'unresolved') {
          fail('admissible-reading-unresolved', `${readingPath}.source`, 'An admissible analysis cannot contain unresolved readings.');
        }
        if (Array.isArray(reading.alternativeReadings)) {
          for (const [alternativeIndex, alternative] of reading.alternativeReadings.entries()) {
            const alternativePath = `${readingPath}.alternativeReadings[${alternativeIndex}]`;
            if (!isObject(alternative)) {
              fail('alternative-shape', alternativePath, 'Alternative reading must be an object.');
              continue;
            }
            if (!PATTERN.test(alternative.pattern || '')) {
              fail('alternative-pattern', `${alternativePath}.pattern`, 'Alternative pattern must contain only - and =.');
            }
            if (alternative.pattern === reading.readingPattern) {
              warn('alternative-duplicate', `${alternativePath}.pattern`, 'Alternative duplicates the selected reading pattern.');
            }
            if (!Array.isArray(alternative.sourceIds) || !alternative.sourceIds.length) {
              fail('alternative-source-ids', `${alternativePath}.sourceIds`, 'Alternative readings require a source id.');
            }
            if (!Array.isArray(alternative.rules) || alternative.rules.some(rule => !/^[a-z0-9-]+$/.test(rule))) {
              fail('alternative-rules', `${alternativePath}.rules`, 'Alternative rules must be lowercase identifiers.');
            }
          }
        }
      }
      if (readings.length && readings.map(reading => reading.readingPattern).join('') !== analysis.actualPattern) {
        fail('analysis-pattern-mismatch', `${analysisPath}.actualPattern`, 'Concatenated reading patterns must equal actualPattern.');
      }
    }

    if (expectation.classification === 'admissible') {
      if (!Array.isArray(expectation.admissibleAnalysisIds) || !expectation.admissibleAnalysisIds.length) {
        fail('admissible-expectation-empty', `${path}.expectation.admissibleAnalysisIds`, 'Admissible items must name at least one admissible analysis.');
      }
    } else if (Array.isArray(expectation.admissibleAnalysisIds) && expectation.admissibleAnalysisIds.length) {
      fail('non-admissible-has-analysis-ids', `${path}.expectation.admissibleAnalysisIds`, 'Non-admissible items must not name admissible analyses.');
    }
    for (const [analysisIndex, analysisId] of (expectation.admissibleAnalysisIds || []).entries()) {
      const analysis = analysisMap.get(analysisId);
      if (!analysis) {
        fail('expectation-analysis-missing', `${path}.expectation.admissibleAnalysisIds[${analysisIndex}]`, `Analysis ${analysisId} does not exist.`);
      } else if (analysis.status !== 'admissible') {
        fail('expectation-analysis-not-admissible', `${path}.expectation.admissibleAnalysisIds[${analysisIndex}]`, `Analysis ${analysisId} is not marked admissible.`);
      }
    }
    if (classification === 'admissible' && !(expectation.admissibleAnalysisIds || []).some(id => {
      const analysis = analysisMap.get(id);
      return analysis && analysis.distance === 0 && analysis.actualPattern === analysis.targetPattern;
    })) {
      fail('admissible-expectation-no-zero-distance', `${path}.expectation`, 'Admissible items need an admissible analysis at distance 0.');
    }
    if (classification === 'invalid-against-target') {
      const targetAnalyses = analyses.filter(analysis => isObject(analysis) && analysis.meterId === target.meterId);
      if (!targetAnalyses.length) {
        fail('invalid-target-no-analysis', `${path}.analyses`, 'Invalid-against-target items need an analysis of the target meter.');
      } else if (targetAnalyses.some(analysis => analysis.status === 'admissible' && analysis.distance === 0)) {
        fail('invalid-target-has-admissible', `${path}.analyses`, 'Invalid-against-target items cannot contain an admissible target analysis.');
      } else if (!targetAnalyses.some(analysis => analysis.status === 'rejected' && analysis.distance > 0)) {
        fail('invalid-target-no-rejection', `${path}.analyses`, 'Invalid-against-target items need a rejected target analysis with positive distance.');
      }
    }
    if (classification === 'invalid-against-all-supported-meters') {
      if (analyses.some(analysis => analysis.status === 'admissible')) {
        fail('invalid-all-has-admissible', `${path}.analyses`, 'Invalid-against-all items cannot contain an admissible analysis.');
      }
      if (!expectation.notes) {
        warn('invalid-all-no-note', `${path}.expectation.notes`, 'Record which supported meters were checked.');
      }
    }
    if (classification === 'unresolved') {
      if (analyses.some(analysis => analysis.status === 'admissible')) {
        fail('unresolved-has-admissible', `${path}.analyses`, 'Unresolved items cannot contain an admissible analysis.');
      }
      const codes = item.uncertainty?.codes;
      if (!Array.isArray(codes) || !codes.length || codes.includes('none')) {
        fail('unresolved-without-uncertainty', `${path}.uncertainty.codes`, 'Unresolved items need a specific uncertainty code.');
      }
    }
    if (classification === 'out-of-scope') {
      if (target.supported === true) {
        fail('out-of-scope-supported', `${path}.target.supported`, 'An out-of-scope item cannot claim a supported form.');
      }
    }

    const decisions = Array.isArray(item.reviewerDecisions) ? item.reviewerDecisions : [];
    if (review.mode === 'unreviewed' && decisions.length) {
      fail('unreviewed-has-decisions', `${path}.reviewerDecisions`, 'Unreviewed items cannot contain reviewer decisions.');
    }
    const decisionReviewers = new Set();
    for (const [decisionIndex, decision] of decisions.entries()) {
      const decisionPath = `${path}.reviewerDecisions[${decisionIndex}]`;
      if (!isObject(decision)) {
        fail('decision-shape', decisionPath, 'Reviewer decision must be an object.');
        continue;
      }
      const reviewer = reviewers.get(decision.reviewerId);
      if (!reviewer) {
        fail('decision-reviewer-unknown', `${decisionPath}.reviewerId`, `Reviewer ${decision.reviewerId} is not declared in benchmark.review.reviewers.`);
      } else {
        decisionReviewers.add(reviewer.id);
      }
      if (!['accept', 'reject', 'dispute', 'abstain'].includes(decision.decision)) {
        fail('decision-value', `${decisionPath}.decision`, 'Reviewer decision is not recognised.');
      }
      if (decision.analysisId !== null && !analysisMap.has(decision.analysisId)) {
        fail('decision-analysis-unknown', `${decisionPath}.analysisId`, `Analysis ${decision.analysisId} does not exist.`);
      }
      if (decision.decision === 'accept' && !decision.analysisId) {
        fail('decision-accept-without-analysis', `${decisionPath}.analysisId`, 'An accept decision must name an analysis.');
      }
      if (!isDate(decision.decidedAt)) {
        fail('decision-date', `${decisionPath}.decidedAt`, 'Decision date must be an ISO date.');
      }
    }
    if (review.mode === 'independent-double') {
      const independentDecisions = [...decisionReviewers].filter(id => reviewers.get(id)?.independent === true);
      if (independentDecisions.length < 2) {
        fail('item-not-double-annotated', `${path}.reviewerDecisions`, 'Independent-double mode requires decisions from two independent reviewers on every item.');
      }
    }

    const adjudication = isObject(item.adjudication) ? item.adjudication : {};
    if (!['not-required', 'pending', 'agreed', 'resolved', 'disputed'].includes(adjudication.status)) {
      fail('adjudication-status', `${path}.adjudication.status`, 'Adjudication status is not recognised.');
    }
    if (adjudication.status === 'pending') anyPendingItem = true;
    if (adjudication.status !== 'pending' && adjudication.status !== 'not-required') {
      if (!adjudication.adjudicatorId) {
        fail('adjudication-missing-adjudicator', `${path}.adjudication.adjudicatorId`, 'Completed adjudication requires an adjudicator.');
      } else {
        const adjudicator = reviewers.get(adjudication.adjudicatorId);
        if (!adjudicator) {
          fail('adjudication-adjudicator-unknown', `${path}.adjudication.adjudicatorId`, 'Adjudicator is not declared in benchmark.review.reviewers.');
        } else if (adjudicator.role !== 'adjudicator' || adjudicator.independent !== true) {
          fail('adjudication-adjudicator-role', `${path}.adjudication.adjudicatorId`, 'Adjudicator must be an independent reviewer with adjudicator role.');
        }
      }
      if (!isDate(adjudication.decidedAt)) {
        fail('adjudication-date', `${path}.adjudication.decidedAt`, 'Completed adjudication requires a decision date.');
      }
    }
    if (adjudication.status === 'agreed' || adjudication.status === 'resolved') {
      if (!adjudication.selectedAnalysisId) {
        fail('adjudication-missing-selection', `${path}.adjudication.selectedAnalysisId`, 'Agreed or resolved adjudication requires a selected analysis.');
      } else {
        const selected = analysisMap.get(adjudication.selectedAnalysisId);
        if (!selected) {
          fail('adjudication-selected-unknown', `${path}.adjudication.selectedAnalysisId`, 'Selected analysis does not exist.');
        } else if (selected.status !== 'admissible') {
          fail('adjudication-selected-not-admissible', `${path}.adjudication.selectedAnalysisId`, 'Selected analysis must be admissible.');
        }
      }
    }
    if (adjudication.status === 'disputed' && adjudication.selectedAnalysisId) {
      fail('disputed-has-selection', `${path}.adjudication.selectedAnalysisId`, 'A disputed item cannot force a selected analysis.');
    }
    if (adjudication.status === 'pending' && adjudication.selectedAnalysisId) {
      fail('pending-has-selection', `${path}.adjudication.selectedAnalysisId`, 'A pending item cannot record a selected analysis.');
    }
    if (adjudication.selectedAnalysisId && !analysisMap.has(adjudication.selectedAnalysisId)) {
      fail('adjudication-selected-unknown', `${path}.adjudication.selectedAnalysisId`, 'Selected analysis does not exist.');
    }

    if (!isObject(item.uncertainty) || !Array.isArray(item.uncertainty.codes) || typeof item.uncertainty.note !== 'string' || !item.uncertainty.note.trim()) {
      fail('uncertainty-shape', `${path}.uncertainty`, 'Uncertainty codes and a note are required.');
    } else {
      const validCodes = new Set(['none', 'word-boundary', 'izafat', 'hamza', 'shadda', 'nasalization', 'aspiration', 'consonant-cluster', 'terminal-pause', 'caesura', 'meter-variant', 'meter-ambiguity', 'source-orthography', 'punctuation', 'unsupported-vocabulary', 'script-variant', 'other']);
      for (const code of item.uncertainty.codes) {
        if (!validCodes.has(code)) fail('uncertainty-code', `${path}.uncertainty.codes`, `Unknown uncertainty code ${code}.`);
      }
      if (item.uncertainty.codes.includes('none') && item.uncertainty.codes.length !== 1) {
        fail('uncertainty-none-exclusive', `${path}.uncertainty.codes`, 'The none code must appear alone.');
      }
    }

    if (target.supported === true) {
      declaredSupportedMeters.add(target.meterId);
      if (expectation.classification === 'admissible' && expectation.goldStatus === 'adjudicated-gold') {
        supportedCounts.set(target.meterId, (supportedCounts.get(target.meterId) || 0) + 1);
      }
    }
    stats.meters[target.meterId] = (stats.meters[target.meterId] || 0) + 1;
  }

  if (review.adjudicationStatus === 'complete' && anyPendingItem) {
    fail('adjudication-status-mismatch', '$.benchmark.review.adjudicationStatus', 'Complete adjudication cannot coexist with pending items.');
  }
  if (review.adjudicationStatus === 'pending' && !anyPendingItem && review.mode !== 'unreviewed') {
    warn('adjudication-status-pending', '$.benchmark.review.adjudicationStatus', 'No item is marked pending despite a pending adjudication status.');
  }
  if (benchmark.status === 'frozen') {
    for (const meterId of declaredSupportedMeters) {
      const count = supportedCounts.get(meterId) || 0;
      if (count < SUPPORTED_METER_MINIMUM) {
        fail('supported-meter-underpowered', '$.items', `Supported meter ${meterId} has ${count} adjudicated gold examples; at least ${SUPPORTED_METER_MINIMUM} are required.`);
      }
    }
    for (const [index, item] of data.items.entries()) {
      if (isObject(item) && item.target?.supported === false) {
        warn('frozen-unsupported-form', `$.items[${index}].target.supported`, 'Frozen benchmark includes an item from a form that is not benchmark-supported.');
      }
    }
  }

  stats.sourceRevisions = revisions.size;
  stats.authors = [...authors].sort();
  return { ok: errors.length === 0, errors, warnings, stats };
}

export async function validateBenchmarkFile(path, options = {}) {
  const data = JSON.parse(readFileSync(path, 'utf8'));
  const meters = options.meters || await loadMeters(options.rootDir || process.cwd());
  return { data, ...validateBenchmark(data, { ...options, meters }) };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const rootDir = process.cwd();
  const file = process.argv.slice(2).find(argument => !argument.startsWith('--')) || 'data/benchmarks/prosody/pilot-2026-10/benchmark.json';
  try {
    const result = await validateBenchmarkFile(resolve(rootDir, file), { rootDir });
    if (result.ok) {
      console.log(`Benchmark valid: ${file}`);
      console.log(`Items ${result.stats.items}, analyses ${result.stats.analyses}, readings ${result.stats.readings}, source revisions ${result.stats.sourceRevisions}`);
      console.log(`Classifications ${JSON.stringify(result.stats.classifications)}`);
      if (result.warnings.length) {
        console.log(`Warnings ${result.warnings.length}`);
        for (const warning of result.warnings) console.log(`  ${warning.code} ${warning.path}: ${warning.message}`);
      }
    } else {
      console.error(`Benchmark invalid: ${file}`);
      for (const error of result.errors) console.error(`  ${error.code} ${error.path}: ${error.message}`);
      if (result.warnings.length) for (const warning of result.warnings) console.log(`  warning ${warning.code} ${warning.path}: ${warning.message}`);
      process.exitCode = 1;
    }
  } catch (error) {
    console.error(`Benchmark validation failed: ${error.message}`);
    process.exitCode = 1;
  }
}
