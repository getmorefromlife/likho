/**
 * Total statistics for the Classical Diwan Corpus.
 */
export function getClassicalDiwanStats(): {
  totalPoets: number;
  totalPoems: number;
  totalCouplets: number;
} {
  let totalPoems = 0;
  let totalCouplets = 0;
  for (const poet of CLASSICAL_DIWAN_POETS) {
    totalPoems += poet.poems.length;
    for (const poem of poet.poems) {
      totalCouplets += poem.couplets.length;
    }
  }
  return {
    totalPoets: CLASSICAL_DIWAN_POETS.length,
    totalPoems,
    totalCouplets,
  };
}

/**
 * Normalizes a word token for matching against classical couplets.
 */
function cleanWordToken(raw: string): string {
  return raw
    .replace(/[،۔؟!؛:«»"()\u200c\u200d\u0640\u0654\u064B-\u0652\u0656-\u0658\u0670]/gu, '')
    .trim();
}

export interface SanadVerseMatch {
  poetName: string;
  poetTakhallus: string;
  poemTitle: string;
  sourceBook: string;
  meterName: string;
  misra1: string;
  misra2: string;
}

let sanadVerseIndex: Map<string, SanadVerseMatch> | null = null;

function buildSanadIndex(): Map<string, SanadVerseMatch> {
  const index = new Map<string, SanadVerseMatch>();
  for (const poet of CLASSICAL_DIWAN_POETS) {
    for (const poem of poet.poems) {
      for (const couplet of poem.couplets) {
        const tokens1 = couplet.misra1.split(/\s+/u).map(cleanWordToken);
        const tokens2 = couplet.misra2.split(/\s+/u).map(cleanWordToken);
        const match: SanadVerseMatch = {
          poetName: poet.name,
          poetTakhallus: poet.takhallus,
          poemTitle: poem.title,
          sourceBook: poem.sourceBook,
          meterName: poem.meterName,
          misra1: couplet.misra1,
          misra2: couplet.misra2,
        };
        for (const token of [...tokens1, ...tokens2]) {
          if (token && token.length >= 2 && !index.has(token)) {
            index.set(token, match);
          }
        }
      }
    }
  }
  return index;
}

/**
 * Finds an authentic Public-Domain illustrative couplet (`شعرِ سند`) containing the searched word.
 */
export function findSanadVerseForWord(rawWord: string): SanadVerseMatch | null {
  const target = cleanWordToken(rawWord);
  if (!target || target.length < 2) return null;

  if (!sanadVerseIndex) {
    sanadVerseIndex = buildSanadIndex();
  }

  const direct = sanadVerseIndex.get(target);
  if (direct) return direct;

  const izafat = sanadVerseIndex.get(`${target}ۂ`);
  if (izafat) return izafat;

  return null;
}
